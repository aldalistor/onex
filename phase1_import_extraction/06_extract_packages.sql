SPOOL ONYX_EXTRACT/package_specs.sql
SELECT '/* PACKAGE SPECIFICATIONS: '||OBJECT_NAME||' */' FROM USER_OBJECTS WHERE OBJECT_TYPE='PACKAGE' ORDER BY OBJECT_NAME;
SELECT DBMS_METADATA.GET_DDL('PACKAGE',OBJECT_NAME) FROM USER_OBJECTS WHERE OBJECT_TYPE='PACKAGE' ORDER BY OBJECT_NAME;
